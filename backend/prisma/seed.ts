async function main() {
  const company = await prisma.company.upsert({
    where: { id: '00000000-0000-0000-0000-000000000001' },
    // "(demo / self-sell)" was an internal label leaking into the owner's own
    // cabinet, where it just reads as confusing clutter — this is a real
    // production company, not a demo, from where the owner sits.
    update: { name: 'Умный Чат' },
    create: {
      id: '00000000-0000-0000-0000-000000000001',
      name: 'Умный Чат',
    },
  });

  const bot = await prisma.bot.upsert({
    where: { widgetToken: DEMO_WIDGET_TOKEN },
    update: {
      systemPrompt: SYSTEM_PROMPT,
      funnelConfig: FUNNEL_CONFIG as any,
      enablesProvisioning: true,
      tracksPayments: true,
      // This bot's funnel is hand-written here, not produced by the async
      // provisioning job — without this, the cabinet status dropdown reads
      // funnelGeneratedAt as null forever and shows "Изучаем ваш бизнес…"
      // indefinitely for a bot that has, in fact, always been fully configured.
      funnelGeneratedAt: new Date(),
    },
    create: {
      companyId: company.id,
      name: 'Alina — Умный Чат self-sell demo bot',
      systemPrompt: SYSTEM_PROMPT,
      funnelConfig: FUNNEL_CONFIG as any,
      widgetToken: DEMO_WIDGET_TOKEN,
      enablesProvisioning: true,
      tracksPayments: true,
      funnelGeneratedAt: new Date(),
    },
  });

  console.log(`Seeded company "${company.name}" and bot "${bot.name}"`);
  console.log(`Demo widget token: ${bot.widgetToken}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
