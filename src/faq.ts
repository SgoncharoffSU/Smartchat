const PROMPT_INJECTION_RE =
  /систем(ную|ный)?\s*(инструкц|промпт)|покажи (свой )?промпт|игнорируй (свои |предыдущие )?инструкции|забудь инструкции|раскрой (свою )?роль|ты теперь|reveal.*prompt|ignore.*instructions/i;

export function isPromptInjectionAttempt(text: string): boolean {
  return PROMPT_INJECTION_RE.test(text);
}

export function matchFaq(text: string): string | null {
  for (const entry of FAQ) {
    if (entry.keywords.test(text)) {
      return entry.answer();
    }
  }
  return null;
}

export function isDeletionRequest(text: string): boolean {
  return /удали(те)? мои данные|удалить данные|сотрите мои данные/i.test(text);
}

export function isRequestForHuman(text: string): boolean {
  return /соедини с человеком|позови человека|нужен человек|живой (менеджер|человек|оператор)|подключи(те)? специалиста/i.test(
    text
  );
}
